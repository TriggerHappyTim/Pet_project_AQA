package com.bft.config;

import com.codeborne.selenide.Configuration;

/**
 * Интерфейс стратегии выполнения тестов
 * 
 * Определяет, как должен выполняться тест в зависимости от типа тестирования
 * (UI, API, мобильный и т.д.). Каждая стратегия инкапсулирует логику настройки
 * окружения, конфигурации Selenide и выполнения действий перед/после тестов.
 * 
 * <p>Реализации стратегий:
 * <ul>
 *   <li>{@link UITestStrategy} - для UI тестирования с использованием браузеров</li>
 *   <li>{@link ApiTestStrategy} - для API тестирования через HTTP запросы</li>
 * </ul>
 * 
 * <p>Пример использования:
 * <pre>{@code
 * TestStrategy strategy = new UITestStrategy(config);
 * strategy.configureEnvironment();
 * strategy.configureSelenide();
 * strategy.beforeTest();
 * // выполнение тестов
 * strategy.afterTest();
 * }</pre>
 * 
 * @author QA Automation Team
 * @version 2.0
 * @see BaseTestStrategy для базовой реализации общих методов
 * @see TestContext для управления стратегиями в контексте тестов
 * @see TestConfiguration для централизованного доступа к стратегиям
 * @since 1.0
 */
public interface TestStrategy {

    /**
     * Настраивает окружение перед выполнением тестов
     * 
     * Выполняет настройку переменных окружения, путей к драйверам,
     * системных свойств и других параметров, необходимых для работы стратегии.
     * 
     * <p>Вызывается один раз при инициализации контекста тестирования.
     * 
     * @see TestContext#initializeEnvironment() для контекста вызова
     */
    void configureEnvironment();

    /**
     * Настраивает Selenide Configuration для данной стратегии
     * 
     * Устанавливает параметры Selenide (браузер, таймауты, размер окна и т.д.)
     * в соответствии с требованиями стратегии.
     * 
     * <p>Вызывается один раз при инициализации контекста тестирования.
     * 
     * @see com.codeborne.selenide.Configuration для всех доступных настроек
     */
    void configureSelenide();

    /**
     * Выполняет действия перед каждым тестом
     * 
     * Вызывается перед каждым тестовым методом. Типичные действия:
     * <ul>
     *   <li>UI: открытие браузера, максимизация окна, настройка КриптоПРО</li>
     *   <li>API: инициализация HTTP клиента, проверка доступности API</li>
     * </ul>
     * 
     * <p>Должен вызываться из {@link org.testng.annotations.BeforeTest}.
     */
    void beforeTest();

    /**
     * Выполняет действия после каждого теста
     * 
     * Вызывается после каждого тестового метода. Типичные действия:
     * <ul>
     *   <li>UI: закрытие браузера, очистка сессии</li>
     *   <li>API: очистка тестовых данных, сброс состояния HTTP клиента</li>
     * </ul>
     * 
     * <p>Должен вызываться из {@link org.testng.annotations.AfterMethod}.
     */
    void afterTest();

    /**
     * Возвращает тип стратегии
     * 
     * @return тип стратегии из {@link TestStrategyType} (UI, API и т.д.)
     * @see TestStrategyType для всех доступных типов
     */
    TestStrategyType getType();

    /**
     * Проверяет, подходит ли стратегия для текущего окружения
     * 
     * Используется для автоматического выбора стратегии. Проверяет доступность
     * ресурсов, необходимых для работы стратегии (браузеры, API endpoints и т.д.).
     * 
     * @return true если стратегия применима для текущего окружения, false в противном случае
     * @see TestContext#selectStrategy(TestConfig) для использования при выборе стратегии
     */
    boolean isApplicable();

    /**
     * Возвращает приоритет стратегии для автоматического выбора
     * 
     * Используется при автоматическом выборе стратегии из нескольких доступных.
     * Стратегия с более высоким приоритетом будет выбрана предпочтительнее.
     * 
     * <p>Рекомендуемые значения:
     * <ul>
     *   <li>UI стратегия: 10 (высокий приоритет)</li>
     *   <li>API стратегия: 5 (средний приоритет)</li>
     * </ul>
     * 
     * @return числовое значение приоритета (больше = выше приоритет)
     * @see TestContext#selectStrategy(TestConfig) для использования при выборе стратегии
     */
    int getPriority();
}