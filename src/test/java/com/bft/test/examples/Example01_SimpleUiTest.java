package com.bft.test.examples;

import com.bft.enums.UIType;
import com.bft.enums.UITypeSelector;
import com.bft.steps.SzvReportsSteps;
import com.bft.test.base.UITestBase;
import io.qameta.allure.AllureId;
import io.qameta.allure.Description;
import io.qameta.allure.Epic;
import io.qameta.allure.Feature;
import io.qameta.allure.Severity;
import io.qameta.allure.SeverityLevel;
import io.qameta.allure.Story;
import org.junit.jupiter.api.Disabled;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * ============================== УЧЕБНЫЙ ПРИМЕР №1 ==============================
 *
 * Самый простой UI-тест: авторизация -> действия на странице -> проверка.
 *
 * КАК ЗАПУСТИТЬ ЭТОТ ПРИМЕР:
 *   1. Уберите аннотацию @Disabled ниже (или запустите метод из IntelliJ IDEA зелёной стрелкой).
 *   2. Выполните команду:  mvn test -Dtest=Example01_SimpleUiTest
 *
 * ПОЧЕМУ КЛАСС ВЫКЛЮЧЕН (@Disabled):
 *   Это учебный пример. Аннотация @Disabled запрещает JUnit запускать тесты класса,
 *   чтобы он случайно не попал в ночной прогон CI. Реальные тесты так не помечают.
 * ==============================================================================
 */
@Disabled("Обучающий пример №1 — не запускать в CI")
@Tag("example")                 // тег "example": можно запустить все примеры разом: mvn test -Dgroups=example
@Epic("Обучение")               // Allure: верхний уровень группировки в отчёте (как «эпик» в Jira)
@Feature("Простые UI тесты")    // Allure: фича внутри эпика
public class Example01_SimpleUiTest extends UITestBase {
    // ↑ extends UITestBase — НАСЛЕДОВАНИЕ ОБЯЗАТЕЛЬНО для любого UI-теста.
    //   Что это даёт «бесплатно»:
    //     • assertions  — объект мягких проверок (см. ниже), создаётся перед каждым тестом;
    //     • logger      — готовый логгер для вывода информации;
    //     • takeScreenshot(name) — сохранить скриншот и приложить к отчёту Allure;
    //     • скриншоты при падении делаются АВТОМАТИЧЕСКИ (MakeScreenshotsExtension);
    //     • браузер открывается/закрывается автоматически до и после каждого теста.

    /**
     * Один метод = один тест = одна проверяемая бизнес-функция.
     * Имя метода должно отвечать на вопрос «что проверяет этот тест».
     */
    @Test                    // ← аннотация JUnit 5: «это тестовый метод, его нужно выполнить»
    @Tag("web")              // ← тег для фильтрации: mvn test -Dgroups=web  или -DexcludedGroups=web
    @AllureId("EXAMPLE-001") // ← уникальный код теста для связи с TMS/Jira. Формат: ПРЕФИКС-НОМЕР
    @Story("Авторизация")    // Allure: пользовательская история
    @Description("Учебный пример: авторизация в ЛК Страхователя через ЕПГУ") // описание в отчёте
    @Severity(SeverityLevel.CRITICAL) // важность теста в отчёте Allure
    public void authorizeAndOpenReportsList() {

        // ---------- ШАГ 1. Создаём объект с шагами ----------
        // «Steps» (шаги) — это классы, которые умеют выполнять бизнес-действия:
        // авторизоваться, открыть нужную вкладку, заполнить форму.
        // Тест НЕ должен сам тыкать в кнопки — только вызывать шаги.
        SzvReportsSteps steps = new SzvReportsSteps();

        // ---------- ШАГ 2. Авторизуемся (Arrange) ----------
        // Контур (тестовый стенд) выбирается автоматически из свойства evs.ui.type.
        // Если хотите задать контур вручную — передайте его явно:
        //   steps.authorizeEVS(UIType.EVS_UAT_LKS);
        // Логин/пароль берутся из credentials.properties или переменных окружения —
        // пароли НИКОГДА не пишутся в коде теста.
        steps.authorizeEVS(UITypeSelector.getSelectedUIType());

        // ---------- ШАГ 3. Бизнес-действия (Act) ----------
        // Каждый вызов — это отдельный шаг в отчёте Allure (аннотация @Step внутри класса шагов).
        steps.addReports();          // открыть «Отчёты» -> «Список отчетов» -> «Добавить отчет»

        // ---------- ШАГ 4. Проверки (Assert) ----------
        // «assertions» достался нам от UITestBase. Это МЯГКИЕ проверки:
        // если проверка провалилась, тест НЕ прерывается сразу — он дописывает ошибку
        // в список и продолжает выполняться, а в конце (автоматически!) все ошибки
        // разом выводятся в результат теста. Поэтому можно проверить сразу много вещей
        // и увидеть ВСЕ проблемы за один прогон.
        //
        // ВАЖНО: вызывать assertions.assertAll() вручную НЕ нужно —
        // BaseTest делает это сам после каждого теста.

        // Пример мягкой проверки (условие, сообщение об ошибке):
        assertions.assertTrue(true,
                "Заглушка: замените на реальную проверку, например видимость таблицы");

        // Пример проверки текста элемента (низкоуровневый доступ допустим для коротких
        // проверок; всё сложное — добавляйте в Page Object / шаги):
        // assertions.assertTrue(
        //         $x("//h1[contains(text(),'Список отчетов')]").isDisplayed(),
        //         "Должен открыться список отчётов");

        // ---------- Итог ----------
        // Если хоть одна проверка провалилась — тест упадёт ПОСЛЕ выполнения всех шагов,
        // к нему автоматически прикрепятся скриншоты и page source.
    }
}
