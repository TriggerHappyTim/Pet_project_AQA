package com.bft.steps;

/**
 * Стратегия ручного заполнения отчёта в UI ЛК Страхователя.
 *
 * <p>Позволяет добавлять новые типы отчётов без правки базового теста: достаточно
 * зарегистрировать реализацию в {@link ReportFillers} для нужного {@link com.bft.enums.ReportFormType}.
 *
 * <p>Два варианта заполнения:
 * <ul>
 *   <li>{@link #fillMinimal} — только обязательные поля (минимально необходимый отчёт);</li>
 *   <li>{@link #fillMaximal} — обязательные + максимально возможные необязательные поля/строки.</li>
 * </ul>
 */
public interface ManualReportFiller {

    /** Заполняет отчёт минимально необходимым набором данных (только обязательные поля). */
    void fillMinimal(SzvReportsSteps steps);

    /** Заполняет отчёт максимально полно (обязательные + необязательные поля/доп. строки). */
    void fillMaximal(SzvReportsSteps steps);

    /**
     * Проверяет, что данные, введённые при заполнении, реально сохранились в черновике
     * (застрахованное лицо/мероприятие/период отображаются на странице).
     *
     * <p>Вызывается базовым тестом {@code AbstractReportUploadSignTest} сразу после
     * {@code verifyNoValidationErrors()}. Каждая стратегия переопределяет под свои
     * заполняемые поля; по умолчанию — без дополнительных проверок.
     */
    default void verifyPersisted(ReportValidationSteps validationSteps) {
        // no-op: отчёт без явного заполнения ЗЛ/периодов не проверяем на сохранение
    }
}
